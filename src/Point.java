public class Point {
    // Aufgabe 3: x und y Koordinaten (Gitter-Koordinaten)
    private int x;
    private int y;

    // Aufgabe 3: Konstruktor
    public Point(int x, int y) {
        this.x = x;
        this.y = y;
    }

    // Aufgabe 3: oeffentliche Getter-Methoden
    public int getX() {
        return x;
    }

    public int getY() {
        return y;
    }
}
